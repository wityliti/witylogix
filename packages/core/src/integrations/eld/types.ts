// ─── Adapter Interface ──────────────────────────────────────

/**
 * Interface that all ELD adapters must implement.
 */
export interface ELDAdapterInterface {
  /** Initialize/authenticate with provider */
  initialize(): Promise<void>;

  /** Get driver logs for a date range */
  getDriverLogs(
    driverId: string,
    startDate: Date,
    endDate: Date
  ): Promise<ELDDriverLog[]>;

  /** Get current duty status for driver */
  getDutyStatus(driverId: string): Promise<ELDDutyStatus>;

  /** Change driver duty status */
  setDutyStatus(
    driverId: string,
    status: DutyStatus,
    location?: { latitude: number; longitude: number }
  ): Promise<ELDDutyStatus>;

  /** Get HOS violations for driver */
  getViolations(driverId: string, days?: number): Promise<ELDViolation[]>;

  /** Get vehicle information */
  getVehicle(vehicleId: string): Promise<ELDVehicle>;

  /** Get list of all vehicles */
  getVehicles(): Promise<ELDVehicle[]>;

  /** Submit DVIR */
  submitDVIR(dvir: Partial<ELDDVIR>): Promise<ELDDVIR>;

  /** Get DVIR records */
  getDVIRs(vehicleId: string, days?: number): Promise<ELDDVIR[]>;

  /** Calculate HOS summary for driver */
  getHOSSummary(
    driverId: string,
    date: Date
  ): Promise<{
    hours11: number;
    hours14: number;
    hours60: number;
    hours70: number;
    availableDriving: number;
    availableOnDuty: number;
  }>;

  /** Handle incoming webhook event */
  handleWebhook(event: ELDWebhookEvent): Promise<void>;

  /** Health check */
  healthCheck(): Promise<boolean>;
}

