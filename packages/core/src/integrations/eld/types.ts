/**
 * ELD (Electronic Logging Device) Adapters — Core type definitions.
 *
 * Defines unified types and interfaces for all ELD integrations:
 * Motive, Omnitracs, Azuga. Implements FMCSA Part 395 HOS compliance rules.
 *
 * - Driver logs, duty status transitions, violations
 * - Vehicle tracking and diagnostics
 * - DVIR (Driver Vehicle Inspection Report) submissions
 * - HOS (Hours of Service) calculation and compliance
 * - Webhook events for real-time updates
 */

// ─── Duty Status Types ──────────────────────────────────────

/** FMCSA Part 395 duty status values */
export type DutyStatus =
  | "driving"
  | "on-duty"
  | "sleeper-berth"
  | "off-duty"
  | "personal-conveyance"
  | "yard-move";

/** Violation type for HOS compliance */
export type ViolationType =
  | "hours-14"
  | "hours-11"
  | "hours-8"
  | "hours-60-70"
  | "break-30min";

/** ELD event type */
export type ELDEventType =
  | "duty-status-change"
  | "location-update"
  | "hos-violation"
  | "dvir-submitted"
  | "fault-code"
  | "diagnostic-event"
  | "driver-cert"
  | "vehicle-cert";

// ─── Driver Log ─────────────────────────────────────────────

/**
 * Standardized driver log record representing a continuous duty period.
 * Normalizes across Motive, Omnitracs, Azuga APIs.
 */
export interface ELDDriverLog {
  /** Unique log ID (generated by ELD provider) */
  id: string;

  /** Tenant/account ID */
  accountId: string;

  /** Driver ID from ELD provider */
  driverId: string;

  /** Vehicle ID from ELD provider */
  vehicleId: string;

  /** Start time of this duty period (ISO 8601) */
  startTime: Date;

  /** End time of this duty period (ISO 8601) */
  endTime: Date;

  /** Duty status during this period */
  dutyStatus: DutyStatus;

  /** Total miles driven (if driving status) */
  miles?: number;

  /** Total hours in this duty period */
  hours: number;

  /** Location details at log start */
  startLocation?: {
    latitude: number;
    longitude: number;
    address?: string;
    city?: string;
    state?: string;
  };

  /** Location details at log end */
  endLocation?: {
    latitude: number;
    longitude: number;
    address?: string;
    city?: string;
    state?: string;
  };

  /** Notes/remarks from driver or ELD */
  remarks?: string;

  /** Sequence number for ordering within a day */
  sequence: number;

  /** Whether this log was edited post-submission */
  edited: boolean;

  /** Timestamp when log was created/submitted */
  createdAt: Date;

  /** Timestamp when log was last updated */
  updatedAt: Date;
}

// ─── Duty Status Record ─────────────────────────────────────

/**
 * Represents a single duty status change event.
 */
export interface ELDDutyStatus {
  /** Unique event ID */
  id: string;

  /** Account ID */
  accountId: string;

  /** Driver ID */
  driverId: string;

  /** Vehicle ID (if applicable) */
  vehicleId?: string;

  /** The new duty status */
  status: DutyStatus;

  /** When the status change occurred */
  changedAt: Date;

  /** Location when status changed */
  location?: {
    latitude: number;
    longitude: number;
    address?: string;
  };

  /** Hours of service available for driving (calculated) */
  availableHoursDriving: number;

  /** Hours of service available on-duty (calculated) */
  availableHoursOnDuty: number;

  /** Timestamp of record creation */
  createdAt: Date;
}

// ─── HOS Violation ──────────────────────────────────────────

/**
 * Represents a detected FMCSA Part 395 HOS violation.
 */
export interface ELDViolation {
  /** Unique violation ID */
  id: string;

  /** Account ID */
  accountId: string;

  /** Driver ID */
  driverId: string;

  /** Vehicle ID (if applicable) */
  vehicleId?: string;

  /** Type of violation */
  violationType: ViolationType;

  /** Human-readable description */
  description: string;

  /** Severity level */
  severity: "warning" | "error" | "critical";

  /** When violation was detected */
  detectedAt: Date;

  /** Time range during which violation occurred */
  violationTimeRange: {
    start: Date;
    end: Date;
  };

  /** Relevant HOS hours at time of violation */
  hosContext: {
    /** Hours driven in 11-hour period */
    hours11?: number;
    /** Hours driven in 14-hour period */
    hours14?: number;
    /** Hours driven in 60-hour period (8 days) */
    hours60?: number;
    /** Hours driven in 70-hour period (8 days) */
    hours70?: number;
    /** Minutes since last 30-minute break */
    minutesSinceBreak?: number;
  };

  /** Whether violation has been acknowledged by driver */
  acknowledged: boolean;

  /** When driver acknowledged (if applicable) */
  acknowledgedAt?: Date;

  /** Timestamp of record creation */
  createdAt: Date;
}

// ─── Vehicle ────────────────────────────────────────────────

/**
 * Standardized vehicle record from ELD provider.
 */
export interface ELDVehicle {
  /** Unique vehicle ID from ELD provider */
  id: string;

  /** Account ID */
  accountId: string;

  /** VIN */
  vin: string;

  /** License plate */
  licensePlate: string;

  /** Make and model */
  make?: string;

  model?: string;

  /** Year */
  year?: number;

  /** Vehicle group/fleet assignment */
  group?: string;

  /** Current odometer reading (miles) */
  odometerMiles?: number;

  /** Fuel type */
  fuelType?: "diesel" | "gasoline" | "electric" | "hybrid";

  /** Capacity (GVWR in lbs) */
  capacityLbs?: number;

  /** Current GPS location */
  currentLocation?: {
    latitude: number;
    longitude: number;
    address?: string;
    updatedAt: Date;
  };

  /** Whether vehicle is currently assigned to a driver */
  driverId?: string;

  /** Active faults/trouble codes */
  activeFaults: string[];

  /** Last inspection date */
  lastInspectionDate?: Date;

  /** Next inspection due date */
  nextInspectionDueDate?: Date;

  /** Maintenance records status */
  maintenanceStatus?: "good" | "pending" | "overdue";

  /** Timestamp of record creation */
  createdAt: Date;

  /** Timestamp of last update */
  updatedAt: Date;
}

// ─── DVIR (Driver Vehicle Inspection Report) ────────────────

/**
 * DVIR submission for vehicle condition documentation.
 * Required by FMCSA 49 CFR 396.11.
 */
export interface ELDDVIR {
  /** Unique DVIR ID */
  id: string;

  /** Account ID */
  accountId: string;

  /** Driver ID who submitted DVIR */
  driverId: string;

  /** Vehicle ID being inspected */
  vehicleId: string;

  /** Inspection time (ISO 8601) */
  inspectionTime: Date;

  /** Type of DVIR: pre-trip or post-trip */
  type: "pre-trip" | "post-trip";

  /** Overall condition: pass, defect, or not-safe */
  condition: "pass" | "defect" | "not-safe";

  /** List of defects found (empty if pass) */
  defects: Array<{
    /** Component or area with defect */
    component: string;
    /** Severity: minor, major, critical */
    severity: "minor" | "major" | "critical";
    /** Description of defect */
    description: string;
    /** Photos/evidence URLs */
    evidenceUrls?: string[];
  }>;

  /** Driver's remarks */
  driverRemarks?: string;

  /** Mechanic review/repair notes (post-submission) */
  mechanicRemarks?: string;

  /** Whether defects were corrected before next trip */
  defectsResolved?: boolean;

  /** Timestamp when DVIR was submitted */
  submittedAt: Date;

  /** Timestamp when last updated */
  updatedAt: Date;
}

// ─── ELD Event ──────────────────────────────────────────────

