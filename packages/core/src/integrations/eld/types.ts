  /** Driver ID (when applicable) */
  driverId?: string;

  /** Vehicle ID (when applicable) */
  vehicleId?: string;

  /** Event timestamp */
  timestamp: Date;

  /** Event-specific data payload */
  data: Record<string, unknown>;

